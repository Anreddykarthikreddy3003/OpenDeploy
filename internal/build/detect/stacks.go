// shellCmd renders a start command as JSON exec form running /bin/sh -c.
func shellCmd(cmd string) string {
	b, _ := json.Marshal([]string{"/bin/sh", "-c", "exec " + cmd})
	return string(b)
}

func header(p *Plan) string {
	return fmt.Sprintf("# Generated by OpenDeploy (stack=%s framework=%s). Review with `opendeployctl plan`.\n", p.Stack, p.Framework)
}

// ---------------------------------------------------------------- Node.js

type packageJSON struct {
	Name            string            `json:"name"`
	Main            string            `json:"main"`
	Scripts         map[string]string `json:"scripts"`
	Dependencies    map[string]string `json:"dependencies"`
	DevDependencies map[string]string `json:"devDependencies"`
	Engines         map[string]string `json:"engines"`
	PackageManager  string            `json:"packageManager"`
	Workspaces      json.RawMessage   `json:"workspaces"`
}

func (p *packageJSON) has(dep string) bool {
	_, a := p.Dependencies[dep]
	_, b := p.DevDependencies[dep]
	return a || b
}

var serverFrameworks = []string{"next", "nuxt", "express", "fastify", "@nestjs/core", "koa", "hono", "@remix-run/serve", "@remix-run/node",
	"@sveltejs/adapter-node", "@angular/ssr", "@astrojs/node", "@hapi/hapi", "@adonisjs/core", "strapi", "@strapi/strapi"}

var staticFrameworks = []struct{ dep, name, dir string }{
	{"@angular/core", "angular", ""},
	{"gatsby", "gatsby", "public"},
	{"astro", "astro", "dist"},
	{"react-scripts", "create-react-app", "build"},
	{"@vue/cli-service", "vue-cli", "dist"},
	{"@docusaurus/core", "docusaurus", "build"},
	{"vitepress", "vitepress", ".vitepress/dist"},
	{"@sveltejs/adapter-static", "sveltekit-static", "build"},
	{"vite", "vite", "dist"},
	{"parcel", "parcel", "dist"},
}

func nodeMajor(spec string) string {
	m := regexp.MustCompile(`(\d{2})`).FindString(spec)
	switch m {
	case "18", "20", "22", "24":
		return m
	}
	if n, err := strconv.Atoi(m); err == nil {
		switch {
		case n >= 24:
			return "24"
		case n >= 22:
			return "22"
		case n >= 20:
			return "20"
		}
	}
	return "22"
}

func detectNode(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.exists("package.json") {
		return false, nil
	}
	var pkg packageJSON
	if err := readJSON(t, "package.json", &pkg); err != nil {
		return false, fmt.Errorf("package.json: %w", err)
	}
	p.Stack = "node"
	p.reason("package.json found")
	if len(pkg.Workspaces) > 0 && string(pkg.Workspaces) != "null" {
		p.warn("package.json declares workspaces; set build.root to the app directory if this is a monorepo")
	}
	version := "22"
	if v := pkg.Engines["node"]; v != "" {
		version = nodeMajor(v)
		p.reason("Node.js %s from engines.node %q", version, v)
	} else if s, err := t.read(".nvmrc"); err == nil {
		version = nodeMajor(strings.TrimSpace(s))
		p.reason("Node.js %s from .nvmrc", version)
	}
	p.RuntimeVersion = version

	pm, install := "npm", "npm install --no-audit --no-fund"
	switch {
	case t.exists("pnpm-lock.yaml") || strings.HasPrefix(pkg.PackageManager, "pnpm"):
		pm, install = "pnpm", "corepack enable && pnpm install --frozen-lockfile"
	case t.exists("bun.lockb") || t.exists("bun.lock") || strings.HasPrefix(pkg.PackageManager, "bun"):
		pm, install = "bun", "bun install --frozen-lockfile"
	case t.exists("yarn.lock") || strings.HasPrefix(pkg.PackageManager, "yarn"):
		pm = "yarn"
		if t.exists(".yarnrc.yml") || strings.HasPrefix(pkg.PackageManager, "yarn@2") || strings.HasPrefix(pkg.PackageManager, "yarn@3") || strings.HasPrefix(pkg.PackageManager, "yarn@4") {
			install = "corepack enable && yarn install --immutable"
		} else {
			install = "corepack enable && yarn install --frozen-lockfile"
		}
	case t.exists("package-lock.json") || t.exists("npm-shrinkwrap.json"):
		install = "npm ci --no-audit --no-fund"
	default:
		p.warn("no lockfile found; dependency versions are not reproducible")
	}
	p.PackageManager = pm
	p.reason("package manager %s", pm)
	run := func(script string) string {
		switch pm {
		case "npm":
			return "npm run " + script
		case "bun":
			return "bun run " + script
		default:
			return pm + " run " + script
		}
	}

	server := false
	for _, f := range serverFrameworks {
		if pkg.has(f) {
			server = true
			if p.Framework == "" {
				p.Framework = strings.TrimPrefix(f, "@")
			}
		}
	}
	if pkg.has("next") {
		p.Framework = "next"
	}
	if pkg.has("nuxt") {
		p.Framework = "nuxt"
	}

	build := ""
	if _, ok := pkg.Scripts["build"]; ok {
		build = run("build")
	}
	if opt.Overrides.BuildCommand != "" {
		build = opt.Overrides.BuildCommand
		p.reason("build command overridden by project administrator")
	}
	p.BuildCommand = build

	if !server {
		for _, sf := range staticFrameworks {
			if !pkg.has(sf.dep) {
				continue
			}
			if _, hasStart := pkg.Scripts["start"]; hasStart && sf.name != "create-react-app" && !isDevServer(pkg.Scripts["start"]) {
				break
			}
			if build == "" {
				return false, fmt.Errorf("%s project has no build script", sf.name)
			}
			dir := sf.dir
			if sf.name == "angular" {
				dir = angularOutput(t, pkg.Name)
			}
			if opt.Overrides.OutputDir != "" {
				dir = opt.Overrides.OutputDir
			} else if opt.Config != nil && opt.Config.Build.OutputDir != "" {
				dir = opt.Config.Build.OutputDir
			}
			p.Framework, p.StaticOutput, p.StaticDir, p.Port = sf.name, true, dir, 0
			p.reason("%s detected with no server runtime: build once and serve %s/ as a static artifact", sf.name, dir)
			p.DockerfileContent = renderNode(p, opt.ImagePrefix, install, "", t.exists(".yarn"))
			p.Generated = true
			return true, nil
		}
	}

	start := ""
	if proc, ok := procfileWeb(t); ok {
		start = proc
		p.reason("start command from Procfile")
	} else if s, ok := pkg.Scripts["start"]; ok && !isDevServer(s) {
		start = run("start")
		p.reason("start command from scripts.start")
	} else if p.Framework == "next" {
		start = "node_modules/.bin/next start -p \"$PORT\""
	} else if p.Framework == "nuxt" {
		start = "node .output/server/index.mjs"
	} else if pkg.Main != "" {
		start = "node " + pkg.Main
		p.reason("start from package.json main")
	} else {
		for _, f := range []string{"server.js", "index.js", "app.js", "main.js", "server.mjs", "index.mjs"} {
			if t.exists(f) {
				start = "node " + f
				p.reason("start from %s", f)
				break
			}
		}
	}
	if opt.Overrides.StartCommand != "" {
		start = opt.Overrides.StartCommand
	}
	if start == "" {
		return false, ErrNeedsWizard
	}
	if pm == "bun" && strings.HasPrefix(start, "node ") {
		start = "bun " + strings.TrimPrefix(start, "node ")
	}
	p.StartCommand = start
	if p.Framework == "next" {
		p.Tmpfs = append(p.Tmpfs, "/app/.next/cache")
	}
	p.DockerfileContent = renderNode(p, opt.ImagePrefix, install, start, t.exists(".yarn"))
	p.Generated = true
	return true, nil
}

func isDevServer(s string) bool {
	return regexp.MustCompile(`\b(vite|webpack-dev-server|react-scripts start|ng serve|gatsby develop|astro dev|parcel(\s+serve)?\s)`).MatchString(s) &&
		!strings.Contains(s, "preview")
}

func angularOutput(t *tree, name string) string {
	var aj struct {
		Projects map[string]struct {
			Architect map[string]struct {
				Builder string          `json:"builder"`
				Options json.RawMessage `json:"options"`
			} `json:"architect"`
		} `json:"projects"`
	}
	if err := readJSON(t, "angular.json", &aj); err != nil || len(aj.Projects) == 0 {
		return "dist/" + name + "/browser"
	}
	keys := make([]string, 0, len(aj.Projects))
	for k := range aj.Projects {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b := aj.Projects[keys[0]].Architect["build"]
	var opts struct {
		OutputPath json.RawMessage `json:"outputPath"`
	}
	_ = json.Unmarshal(b.Options, &opts)
	var out string
	if err := json.Unmarshal(opts.OutputPath, &out); err != nil {
		var obj struct {
			Base string `json:"base"`
		}
		_ = json.Unmarshal(opts.OutputPath, &obj)
		out = obj.Base
	}
	if out == "" {
		out = "dist/" + keys[0]
	}
	if strings.Contains(b.Builder, ":application") {
		out += "/browser"
	}
	return out
}

func renderNode(p *Plan, prefix, install, start string, hasYarnDir bool) string {
	img := image(prefix, "node", p.RuntimeVersion)
	if p.PackageManager == "bun" {
		img = image(prefix, "bun", "")
	}
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS deps\nWORKDIR /app\n", img)
	b.WriteString("COPY package.json package-lock.json* npm-shrinkwrap.json* yarn.lock* pnpm-lock.yaml* bun.lockb* bun.lock* .yarnrc.yml* ./\n")
	if p.PackageManager == "yarn" && hasYarnDir {
		b.WriteString("COPY .yarn ./.yarn\n")
	}
	fmt.Fprintf(&b, "RUN --mount=type=cache,target=/root/.npm --mount=type=cache,target=/root/.cache %s && mkdir -p node_modules\n\n", install)
	fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /app\nCOPY --from=deps /app/node_modules ./node_modules\nCOPY . .\n", img)
	if p.BuildCommand != "" {
		fmt.Fprintf(&b, "RUN %s\n", p.BuildCommand)
	}
	if p.StaticOutput {
		fmt.Fprintf(&b, "\nFROM scratch AS static\nCOPY --from=build /app/%s/ /\n", filepath.ToSlash(filepath.Clean(p.StaticDir)))
		return b.String()
	}
	if p.PackageManager == "npm" {
		b.WriteString("RUN npm prune --omit=dev --no-audit --no-fund || true\n")
	}
	fmt.Fprintf(&b, "\nFROM %s AS runtime\nWORKDIR /app\nENV NODE_ENV=production PORT=%d HOSTNAME=0.0.0.0\n", img, p.Port)
	b.WriteString("COPY --from=build --chown=10001:10001 /app ./\nUSER 10001:10001\n")
	fmt.Fprintf(&b, "EXPOSE %d\nCMD %s\n", p.Port, shellCmd(start))
	return b.String()
}

// ---------------------------------------------------------------- Python

var pyAppRE = regexp.MustCompile(`(?m)^\s*(\w+)\s*(?::\s*\w+\s*)?=\s*(FastAPI|Flask|Starlette|Quart)\(`)

func detectPython(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.anyExists("requirements.txt", "pyproject.toml", "Pipfile", "setup.py") {
		return false, nil
	}
	p.Stack = "python"
	version := "3.12"
	if s, err := t.read(".python-version"); err == nil {
		if m := regexp.MustCompile(`3\.\d{1,2}`).FindString(s); m != "" {
			version = m
		}
	} else if s, err := t.read("runtime.txt"); err == nil {
		if m := regexp.MustCompile(`3\.\d{1,2}`).FindString(s); m != "" {
			version = m
		}
	}
	p.RuntimeVersion = version
	p.reason("Python %s", version)

	reqs, _ := t.read("requirements.txt")
	pyproject, _ := t.read("pyproject.toml")
	pipfile, _ := t.read("Pipfile")
	all := strings.ToLower(reqs + "\n" + pyproject + "\n" + pipfile)
	hasDep := func(n string) bool {
		return regexp.MustCompile(`(?m)(^|["'\s])` + regexp.QuoteMeta(n) + `([\s"'=<>~!\[;,]|$)`).MatchString(all)
	}

	var install string
	switch {
	case t.exists("uv.lock"):
		p.PackageManager = "uv"
		install = "pip install uv && UV_PROJECT_ENVIRONMENT=/venv uv sync --frozen --no-dev --no-install-project && (UV_PROJECT_ENVIRONMENT=/venv uv sync --frozen --no-dev || true)"
	case t.exists("poetry.lock"):
		p.PackageManager = "poetry"
		install = "pip install poetry && poetry config virtualenvs.create false && poetry install --only main --no-interaction --no-root"
	case t.exists("Pipfile"):
		p.PackageManager = "pipenv"
		install = "pip install pipenv && pipenv install --system --deploy"
	case t.exists("requirements.txt"):
		p.PackageManager = "pip"
		install = "pip install -r requirements.txt"
	default:
		p.PackageManager = "pip"
		install = "pip install ."
	}
	p.reason("dependencies installed with %s", p.PackageManager)

	extra := []string{}
	start := ""
	if proc, ok := procfileWeb(t); ok {
		start = proc
		p.reason("start command from Procfile")
	} else if t.exists("manage.py") {
		p.Framework = "django"
		wsgi := t.walkFind("wsgi.py", 2)
		if len(wsgi) == 0 {
			return false, fmt.Errorf("django project without wsgi.py")
		}
		mod := strings.TrimSuffix(filepath.ToSlash(wsgi[0]), ".py")
		mod = strings.ReplaceAll(mod, "/", ".")
		start = fmt.Sprintf("gunicorn %s:application --bind 0.0.0.0:$PORT --workers 2 --access-logfile -", mod)
		if !hasDep("gunicorn") {
			extra = append(extra, "gunicorn")
			p.warn("gunicorn not in dependencies; installing it for production serving")
		}
		p.reason("Django project (%s)", mod)
	} else {
		for _, f := range []string{"main.py", "app.py", "app/main.py", "src/main.py", "server.py", "api/main.py", "wsgi.py", "asgi.py"} {
			src, err := t.read(f)
			if err != nil {
				continue
			}
			m := pyAppRE.FindStringSubmatch(src)
			if m == nil {
				continue
			}
			mod := strings.ReplaceAll(strings.TrimSuffix(f, ".py"), "/", ".")
			switch m[2] {
			case "Flask":
				p.Framework = "flask"
				start = fmt.Sprintf("gunicorn %s:%s --bind 0.0.0.0:$PORT --workers 2 --access-logfile -", mod, m[1])
				if !hasDep("gunicorn") {
					extra = append(extra, "gunicorn")
				}
			default:
				p.Framework = strings.ToLower(m[2])
				start = fmt.Sprintf("uvicorn %s:%s --host 0.0.0.0 --port $PORT --proxy-headers", mod, m[1])
				if !hasDep("uvicorn") {
					extra = append(extra, "uvicorn")
				}
			}
			p.reason("%s application %s in %s", p.Framework, m[1], f)
			break
		}
		if start == "" {
			for _, f := range []string{"main.py", "app.py", "server.py"} {
				if t.exists(f) {
					start = "python " + f
					p.reason("start from %s", f)
					break
				}
			}
		}
	}
	if opt.Overrides.StartCommand != "" {
		start = opt.Overrides.StartCommand
	}
	if start == "" {
		return false, ErrNeedsWizard
	}
	p.StartCommand = start
	if opt.Overrides.BuildCommand != "" {
		p.BuildCommand = opt.Overrides.BuildCommand
	}
	img := image(opt.ImagePrefix, "python", version)
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nENV PIP_DISABLE_PIP_VERSION_CHECK=1 PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 VIRTUAL_ENV=/venv PATH=/venv/bin:$PATH\n", img)
	b.WriteString("RUN python -m venv /venv\nWORKDIR /app\n")
	b.WriteString("COPY . .\n")
	fmt.Fprintf(&b, "RUN --mount=type=cache,target=/root/.cache %s\n", install)
	if len(extra) > 0 {
		fmt.Fprintf(&b, "RUN --mount=type=cache,target=/root/.cache pip install %s\n", strings.Join(extra, " "))
	}
	if p.Framework == "django" {
		b.WriteString("RUN python manage.py collectstatic --noinput >/dev/null 2>&1 || true\n")
	}
	if p.BuildCommand != "" {
		fmt.Fprintf(&b, "RUN %s\n", p.BuildCommand)
	}
	fmt.Fprintf(&b, "\nFROM %s AS runtime\nENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 VIRTUAL_ENV=/venv PATH=/venv/bin:$PATH PORT=%d\n", img, p.Port)
	b.WriteString("COPY --from=build /venv /venv\nCOPY --from=build --chown=10001:10001 /app /app\nWORKDIR /app\nUSER 10001:10001\n")
	fmt.Fprintf(&b, "EXPOSE %d\nCMD %s\n", p.Port, shellCmd(start))
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- Go

func detectGo(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.exists("go.mod") {
		return false, nil
	}
	p.Stack = "go"
	mod, _ := t.read("go.mod")
	version := "1.23"
	if m := regexp.MustCompile(`(?m)^go\s+(1\.\d+)`).FindStringSubmatch(mod); m != nil {
		version = m[1]
	}
	if m := regexp.MustCompile(`(?m)^toolchain\s+go(1\.\d+)`).FindStringSubmatch(mod); m != nil {
		version = m[1]
	}
	p.RuntimeVersion = version
	p.reason("Go %s from go.mod", version)
	pkg := ""
	if hasMainPackage(t, ".") {
		pkg = "."
	} else {
		cmds := t.glob("cmd", "*")
		var mains []string
		for _, c := range cmds {
			if hasMainPackage(t, c) {
				mains = append(mains, c)
			}
		}
		modName := ""
		if m := regexp.MustCompile(`(?m)^module\s+(\S+)`).FindStringSubmatch(mod); m != nil {
			modName = filepath.Base(m[1])
		}
		switch {
		case len(mains) == 1:
			pkg = "./" + mains[0]
		case len(mains) > 1:
			for _, pref := range []string{modName, "server", "api", "web", "app"} {
				for _, m := range mains {
					if filepath.Base(m) == pref {
						pkg = "./" + m
					}
				}
				if pkg != "" {
					break
				}
			}
			if pkg == "" {
				return false, fmt.Errorf("multiple Go commands (%s); set build overrides to choose one", strings.Join(mains, ", "))
			}
		}
	}
	if opt.Overrides.BuildCommand != "" {
		pkg = ""
	}
	if pkg == "" && opt.Overrides.BuildCommand == "" {
		return false, ErrNeedsWizard
	}
	p.reason("main package %s", pkg)
	build := fmt.Sprintf("CGO_ENABLED=0 go build -trimpath -ldflags='-s -w' -o /out/app %s", pkg)
	if opt.Overrides.BuildCommand != "" {
		build = opt.Overrides.BuildCommand
	}
	p.BuildCommand = build
	p.StartCommand = "/app"
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /src\nENV GOTOOLCHAIN=auto\n", image(opt.ImagePrefix, "golang", version))
	b.WriteString("COPY go.mod go.sum* ./\nRUN --mount=type=cache,target=/go/pkg/mod go mod download\nCOPY . .\n")
	fmt.Fprintf(&b, "RUN --mount=type=cache,target=/go/pkg/mod --mount=type=cache,target=/root/.cache/go-build mkdir -p /out && %s\n\n", build)
	fmt.Fprintf(&b, "FROM %s AS runtime\nCOPY --from=build /out/app /app\nENV PORT=%d\nUSER 65532:65532\nEXPOSE %d\n", image(opt.ImagePrefix, "go-runtime", ""), p.Port, p.Port)
	if opt.Overrides.StartCommand != "" {
		p.warn("distroless Go runtime has no shell; start command override ignored")
	}
	b.WriteString("ENTRYPOINT [\"/app\"]\n")
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

func hasMainPackage(t *tree, dir string) bool {
	for _, f := range t.glob(dir, "*.go") {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		s, err := t.read(f)
		if err == nil && regexp.MustCompile(`(?m)^package\s+main\b`).MatchString(s) {
			return true
		}
	}
	return false
}

// ---------------------------------------------------------------- Java / Kotlin

func detectJava(t *tree, p *Plan, opt Options) (bool, error) {
	maven := t.exists("pom.xml")
	gradle := t.anyExists("build.gradle", "build.gradle.kts")
	if !maven && !gradle {
		return false, nil
	}
	p.Stack = "java"
	java := "21"
	src := ""
	if maven {
		src, _ = t.read("pom.xml")
	} else if s, err := t.read("build.gradle.kts"); err == nil {
		src = s
	} else {
		src, _ = t.read("build.gradle")
	}
	for _, re := range []string{`<java\.version>\s*(\d+)`, `<maven\.compiler\.release>\s*(\d+)`, `<release>\s*(\d+)`, `JavaVersion\.VERSION_(\d+)`, `languageVersion\.set\(JavaLanguageVersion\.of\((\d+)\)`, `languageVersion\s*=\s*JavaLanguageVersion\.of\((\d+)\)`} {
		if m := regexp.MustCompile(re).FindStringSubmatch(src); m != nil {
			java = m[1]
			break
		}
	}
	switch java {
	case "8", "11", "17", "21", "25":
	default:
		if n, _ := strconv.Atoi(java); n > 21 {
			java = "21"
		} else {
			java = "17"
		}
	}
	p.RuntimeVersion = java
	if strings.Contains(src, "spring-boot") || strings.Contains(src, "org.springframework.boot") {
		p.Framework = "spring-boot"
	} else if strings.Contains(src, "quarkus") {
		p.Framework = "quarkus"
	} else if strings.Contains(src, "micronaut") {
		p.Framework = "micronaut"
	}
	var buildImg, build, jarGlob string
	if maven {
		buildImg = image(opt.ImagePrefix, "maven", java)
		build = "mvn -B -q -DskipTests package"
		if t.exists("mvnw") {
			build = "chmod +x mvnw && ./mvnw -B -q -DskipTests package"
		}
		jarGlob = "target"
		p.PackageManager = "maven"
	} else {
		buildImg = image(opt.ImagePrefix, "gradle", java)
		build = "gradle build -x test --no-daemon -q"
		if t.exists("gradlew") {
			build = "chmod +x gradlew && ./gradlew build -x test --no-daemon -q"
		}
		jarGlob = "build/libs"
		p.PackageManager = "gradle"
	}
	if opt.Overrides.BuildCommand != "" {
		build = opt.Overrides.BuildCommand
	}
	p.BuildCommand = build
	p.reason("Java %s with %s", java, p.PackageManager)
	start := "java -Dserver.port=$PORT -jar /app/app.jar"
	if p.Framework == "quarkus" {
		start = "java -Dquarkus.http.port=$PORT -jar /app/app.jar"
	}
	if proc, ok := procfileWeb(t); ok {
		start = proc
	}
	if opt.Overrides.StartCommand != "" {
		start = opt.Overrides.StartCommand
	}
	p.StartCommand = start
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /src\nCOPY . .\n", buildImg)
	fmt.Fprintf(&b, "RUN --mount=type=cache,target=/root/.m2 --mount=type=cache,target=/root/.gradle %s\n", build)
	fmt.Fprintf(&b, "RUN set -e; f=$(ls -S %s/*.jar 2>/dev/null | grep -v -E '(-plain|-sources|-javadoc|-tests)\\.jar$' | head -n1); test -n \"$f\" || (echo 'no runnable jar produced' >&2; exit 1); mkdir -p /out && cp \"$f\" /out/app.jar\n\n", jarGlob)
	fmt.Fprintf(&b, "FROM %s AS runtime\nWORKDIR /app\nCOPY --from=build /out/app.jar /app/app.jar\n", image(opt.ImagePrefix, "jre", java))
	fmt.Fprintf(&b, "ENV PORT=%d JAVA_TOOL_OPTIONS=\"-XX:MaxRAMPercentage=75 -Djava.io.tmpdir=/tmp\"\nUSER 10001:10001\nEXPOSE %d\nCMD %s\n", p.Port, p.Port, shellCmd(start))
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- .NET

func detectDotnet(t *tree, p *Plan, opt Options) (bool, error) {
	var csprojs []string
	for _, ext := range []string{"*.csproj", "*.fsproj"} {
		csprojs = append(csprojs, t.glob(".", ext)...)
		for _, d := range t.glob(".", "*") {
			csprojs = append(csprojs, t.glob(d, ext)...)
			for _, d2 := range t.glob(d, "*") {
				csprojs = append(csprojs, t.glob(d2, ext)...)
			}
		}
	}
	if len(csprojs) == 0 {
		return false, nil
	}
	p.Stack = "dotnet"
	chosen := ""
	for _, c := range csprojs {
		s, _ := t.read(c)
		if strings.Contains(s, "Microsoft.NET.Sdk.Web") {
			chosen = c
			break
		}
	}
	if chosen == "" {
		if len(csprojs) > 1 {
			return false, fmt.Errorf("multiple .NET projects and none is a web SDK project: %s", strings.Join(csprojs, ", "))
		}
		chosen = csprojs[0]
	}
	src, _ := t.read(chosen)
	version := "8.0"
	if m := regexp.MustCompile(`<TargetFramework>net(\d+\.\d+)`).FindStringSubmatch(src); m != nil {
		version = m[1]
	}
	name := strings.TrimSuffix(filepath.Base(chosen), filepath.Ext(chosen))
	if m := regexp.MustCompile(`<AssemblyName>([A-Za-z0-9_.-]+)</AssemblyName>`).FindStringSubmatch(src); m != nil {
		name = m[1]
	}
	p.RuntimeVersion = version
	p.reason(".NET %s project %s", version, chosen)
	p.BuildCommand = fmt.Sprintf("dotnet publish %q -c Release -o /out", filepath.ToSlash(chosen))
	p.StartCommand = "dotnet /app/" + name + ".dll"
	if opt.Overrides.StartCommand != "" {
		p.StartCommand = opt.Overrides.StartCommand
	}
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /src\nCOPY . .\n", image(opt.ImagePrefix, "dotnet-sdk", version))
	fmt.Fprintf(&b, "RUN --mount=type=cache,target=/root/.nuget/packages %s\n\n", p.BuildCommand)
	fmt.Fprintf(&b, "FROM %s AS runtime\nWORKDIR /app\nCOPY --from=build /out /app\n", image(opt.ImagePrefix, "dotnet-aspnet", version))
	fmt.Fprintf(&b, "ENV PORT=%d ASPNETCORE_URLS=http://+:%d DOTNET_RUNNING_IN_CONTAINER=true DOTNET_EnableDiagnostics=0\nUSER 10001:10001\nEXPOSE %d\nCMD %s\n", p.Port, p.Port, p.Port, shellCmd(p.StartCommand))
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- Ruby

func detectRuby(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.exists("Gemfile") {
		return false, nil
	}
	p.Stack = "ruby"
	gem, _ := t.read("Gemfile")
	version := "3.3"
	if s, err := t.read(".ruby-version"); err == nil {
		if m := regexp.MustCompile(`(\d\.\d)`).FindString(s); m != "" {
			version = m
		}
	} else if m := regexp.MustCompile(`(?m)^\s*ruby\s+["'](\d\.\d)`).FindStringSubmatch(gem); m != nil {
		version = m[1]
	}
	p.RuntimeVersion = version
	start := ""
	if proc, ok := procfileWeb(t); ok {
		start = proc
	} else if t.exists("config/application.rb") || strings.Contains(gem, "'rails'") || strings.Contains(gem, "\"rails\"") {
		p.Framework = "rails"
		start = "bundle exec rails server -b 0.0.0.0 -p $PORT"
		p.Tmpfs = append(p.Tmpfs, "/app/tmp", "/app/log")
	} else if t.exists("config.ru") {
		p.Framework = "rack"
		start = "bundle exec rackup -o 0.0.0.0 -p $PORT"
	}
	if opt.Overrides.StartCommand != "" {
		start = opt.Overrides.StartCommand
	}
	if start == "" {
		return false, ErrNeedsWizard
	}
	p.StartCommand = start
	p.reason("Ruby %s (%s)", version, p.Framework)
	img := image(opt.ImagePrefix, "ruby", version)
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\n", img)
	b.WriteString("RUN apt-get update && apt-get install -y --no-install-recommends build-essential git libpq-dev libyaml-dev pkg-config && rm -rf /var/lib/apt/lists/*\n")
	b.WriteString("WORKDIR /app\nENV BUNDLE_WITHOUT=development:test BUNDLE_PATH=/usr/local/bundle\nCOPY Gemfile Gemfile.lock* ./\n")
	b.WriteString("RUN --mount=type=cache,target=/root/.cache bundle install --jobs 4\nCOPY . .\n")
	if p.Framework == "rails" {
		b.WriteString("RUN SECRET_KEY_BASE_DUMMY=1 RAILS_ENV=production bundle exec rails assets:precompile >/dev/null 2>&1 || true\n")
	}
	fmt.Fprintf(&b, "\nFROM %s AS runtime\n", img)
	b.WriteString("RUN apt-get update && apt-get install -y --no-install-recommends libpq5 libyaml-0-2 && rm -rf /var/lib/apt/lists/*\n")
	b.WriteString("COPY --from=build /usr/local/bundle /usr/local/bundle\nCOPY --from=build --chown=10001:10001 /app /app\nWORKDIR /app\n")
	fmt.Fprintf(&b, "ENV RAILS_ENV=production RACK_ENV=production BUNDLE_WITHOUT=development:test BUNDLE_PATH=/usr/local/bundle RAILS_LOG_TO_STDOUT=1 RAILS_SERVE_STATIC_FILES=1 PORT=%d\nUSER 10001:10001\nEXPOSE %d\nCMD %s\n", p.Port, p.Port, shellCmd(start))
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- PHP

func detectPHP(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.anyExists("composer.json", "index.php", "public/index.php") {
		return false, nil
	}
	p.Stack = "php"
	version := "8.3"
	if s, err := t.read("composer.json"); err == nil {
		var cj struct {
			Require map[string]string `json:"require"`
		}
		_ = json.Unmarshal([]byte(s), &cj)
		if m := regexp.MustCompile(`8\.[1-4]`).FindString(cj.Require["php"]); m != "" {
			version = m
		}
		if _, ok := cj.Require["laravel/framework"]; ok {
			p.Framework = "laravel"
		} else if _, ok := cj.Require["symfony/framework-bundle"]; ok {
			p.Framework = "symfony"
		}
	}
	p.RuntimeVersion = version
	docroot := "/var/www/app"
	if t.exists("public/index.php") || t.exists("public/index.html") {
		docroot = "/var/www/app/public"
	}
	p.reason("PHP %s served by Apache (docroot %s)", version, docroot)
	p.StartCommand = "apache2-foreground"
	p.Tmpfs = append(p.Tmpfs, "/var/run/apache2", "/var/lock/apache2")
	if p.Framework == "laravel" {
		p.Tmpfs = append(p.Tmpfs, "/var/www/app/storage/framework", "/var/www/app/bootstrap/cache")
		p.warn("Laravel storage/ should be a persistent volume for uploads and sessions")
	}
	var b strings.Builder
	b.WriteString(header(p))
	composer := t.exists("composer.json")
	if composer {
		fmt.Fprintf(&b, "FROM %s AS vendor\nWORKDIR /app\nCOPY composer.json composer.lock* ./\n", image(opt.ImagePrefix, "composer", ""))
		b.WriteString("RUN --mount=type=cache,target=/tmp/cache composer install --no-dev --no-scripts --no-interaction --prefer-dist --ignore-platform-reqs --no-autoloader\n")
		b.WriteString("COPY . .\nRUN composer dump-autoload --optimize --no-dev --classmap-authoritative\n\n")
	}
	fmt.Fprintf(&b, "FROM %s AS runtime\n", image(opt.ImagePrefix, "php", version))
	b.WriteString("RUN a2enmod rewrite headers && docker-php-ext-install pdo_mysql opcache >/dev/null && \\\n")
	fmt.Fprintf(&b, "    sed -ri 's!/var/www/html!%s!g' /etc/apache2/sites-available/*.conf /etc/apache2/apache2.conf && \\\n", docroot)
	b.WriteString("    sed -ri 's/^Listen 80$/Listen ${PORT}/' /etc/apache2/ports.conf && \\\n")
	b.WriteString("    sed -ri 's/<VirtualHost \\*:80>/<VirtualHost *:${PORT}>/' /etc/apache2/sites-available/000-default.conf && \\\n")
	b.WriteString("    sed -ri 's/AllowOverride None/AllowOverride All/' /etc/apache2/apache2.conf\n")
	b.WriteString("WORKDIR /var/www/app\n")
	if composer {
		b.WriteString("COPY --from=vendor --chown=10001:10001 /app /var/www/app\n")
	} else {
		b.WriteString("COPY --chown=10001:10001 . /var/www/app\n")
	}
	fmt.Fprintf(&b, "ENV PORT=%d APACHE_PID_FILE=/var/run/apache2/apache2.pid\nUSER 10001:10001\nEXPOSE %d\nCMD [\"apache2-foreground\"]\n", p.Port, p.Port)
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- Rust

func detectRust(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.exists("Cargo.toml") {
		return false, nil
	}
	p.Stack = "rust"
	cargo, _ := t.read("Cargo.toml")
	bin := ""
	if m := regexp.MustCompile(`(?s)\[\[bin\]\].*?name\s*=\s*"([A-Za-z0-9_-]+)"`).FindStringSubmatch(cargo); m != nil {
		bin = m[1]
	} else if m := regexp.MustCompile(`(?s)\[package\].*?name\s*=\s*"([A-Za-z0-9_-]+)"`).FindStringSubmatch(cargo); m != nil {
		bin = m[1]
	}
	if bin == "" {
		return false, fmt.Errorf("Cargo.toml has no package/bin name (workspace root?); set build.root to the binary crate")
	}
	for _, fw := range []string{"axum", "actix-web", "rocket", "warp", "poem"} {
		if strings.Contains(cargo, fw) {
			p.Framework = fw
			break
		}
	}
	locked := ""
	if t.exists("Cargo.lock") {
		locked = " --locked"
	}
	p.RuntimeVersion = "1"
	p.BuildCommand = "cargo build --release" + locked
	p.StartCommand = "/usr/local/bin/app"
	p.reason("Rust binary %s", bin)
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /src\nRUN apt-get update && apt-get install -y --no-install-recommends pkg-config libssl-dev && rm -rf /var/lib/apt/lists/*\nCOPY . .\n", image(opt.ImagePrefix, "rust", "1"))
	fmt.Fprintf(&b, "RUN --mount=type=cache,target=/usr/local/cargo/registry --mount=type=cache,target=/src/target %s && mkdir -p /out && cp target/release/%s /out/app\n\n", p.BuildCommand, bin)
	fmt.Fprintf(&b, "FROM %s AS runtime\nRUN apt-get update && apt-get install -y --no-install-recommends ca-certificates libssl3 && rm -rf /var/lib/apt/lists/*\n", image(opt.ImagePrefix, "debian", ""))
	fmt.Fprintf(&b, "COPY --from=build /out/app /usr/local/bin/app\nENV PORT=%d\nUSER 10001:10001\nEXPOSE %d\nCMD [\"/usr/local/bin/app\"]\n", p.Port, p.Port)
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- Elixir

func detectElixir(t *tree, p *Plan, opt Options) (bool, error) {
	if !t.exists("mix.exs") {
		return false, nil
	}
	p.Stack = "elixir"
	mix, _ := t.read("mix.exs")
	m := regexp.MustCompile(`app:\s*:([a-z0-9_]+)`).FindStringSubmatch(mix)
	if m == nil {
		return false, fmt.Errorf("mix.exs: cannot determine app name")
	}
	app := m[1]
	if strings.Contains(mix, ":phoenix") {
		p.Framework = "phoenix"
	}
	p.RuntimeVersion = "1.17"
	p.StartCommand = "/app/bin/" + app + " start"
	p.Tmpfs = append(p.Tmpfs, "/app/tmp")
	p.reason("Elixir release %s", app)
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nRUN apt-get update && apt-get install -y --no-install-recommends build-essential git && rm -rf /var/lib/apt/lists/*\n", image(opt.ImagePrefix, "elixir", "1.17"))
	b.WriteString("WORKDIR /app\nENV MIX_ENV=prod\nRUN mix local.hex --force && mix local.rebar --force\nCOPY mix.exs mix.lock* ./\nRUN mix deps.get --only prod && mix deps.compile\nCOPY . .\n")
	if p.Framework == "phoenix" {
		b.WriteString("RUN mix assets.deploy >/dev/null 2>&1 || true\n")
	}
	b.WriteString("RUN mix compile && mix release --overwrite\n\n")
	fmt.Fprintf(&b, "FROM %s AS runtime\nRUN apt-get update && apt-get install -y --no-install-recommends libstdc++6 openssl libncurses6 locales ca-certificates && rm -rf /var/lib/apt/lists/*\n", image(opt.ImagePrefix, "debian", ""))
	fmt.Fprintf(&b, "ENV LANG=C.UTF-8 MIX_ENV=prod PHX_SERVER=true RELEASE_TMP=/app/tmp PORT=%d\nCOPY --from=build --chown=10001:10001 /app/_build/prod/rel/%s /app\nUSER 10001:10001\nEXPOSE %d\nCMD %s\n", p.Port, app, p.Port, shellCmd(p.StartCommand))
	p.DockerfileContent = b.String()
	p.Generated = true
	return true, nil
}

// ---------------------------------------------------------------- manual

func renderCustom(p *Plan, prefix string) string {
	var b strings.Builder
	b.WriteString(header(p))
	fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /app\nCOPY . .\n", image(prefix, "debian", ""))
	if p.BuildCommand != "" {
		fmt.Fprintf(&b, "RUN %s\n", p.BuildCommand)
	}
	if p.StaticOutput {
		fmt.Fprintf(&b, "\nFROM scratch AS static\nCOPY --from=build /app/%s/ /\n", filepath.ToSlash(filepath.Clean(p.StaticDir)))
		return b.String()
	}
	fmt.Fprintf(&b, "RUN chown -R 10001:10001 /app\nENV PORT=%d\nUSER 10001:10001\nEXPOSE %d\nCMD %s\n", p.Port, p.Port, shellCmd(p.StartCommand))
	return b.String()
}
